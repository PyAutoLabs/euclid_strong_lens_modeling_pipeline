def _write_meta(path, **kw):
    meta = dict(status="drop", positions_used=[[1.0, 0.5], [-0.9, -0.4]], threshold=0.34)
    meta.update(kw)
    (Path(path) / gate.META_NAME).write_text(json.dumps(meta))


def test_util_meta_absent_means_default_behaviour(tmp_path):
    import util

    assert util.positions_likelihood_list_from_meta(tmp_path) == (False, None)


def test_util_meta_uses_positions_and_threshold(tmp_path):
    import util

    _write_meta(tmp_path)
    found, lh = util.positions_likelihood_list_from_meta(tmp_path)
    assert found and len(lh) == 1
    assert lh[0].threshold == pytest.approx(0.34)
    assert np.asarray(lh[0].positions).tolist() == [[1.0, 0.5], [-0.9, -0.4]]


def test_util_meta_n_lt_2_turns_the_penalty_off(tmp_path):
    import util

    _write_meta(tmp_path, status="n_lt_2", positions_used=[[1.0, 0.5]], threshold=None)
    assert util.positions_likelihood_list_from_meta(tmp_path) == (True, None)


