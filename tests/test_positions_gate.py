def _loo(s, J):
    return [dict(s_min=a, J=b, params=[0.0] * 5, params_J=[0.0] * 5) for a, b in zip(s, J)]


# Radii from the centre: 1.0, 1.1, 1.2, 1.3 (none inner, none outer).
RING = np.array([[1.0, 0.0], [0.0, 1.1], [-1.2, 0.0], [0.0, -1.3]])
FAIL = dict(s_min=0.8, J=300.0)


def test_single_candidate_is_dropped():
    d = gate.outlier_drop(RING, (0, 0), FAIL, _loo([0.9, 0.05, 0.9, 0.9], [9, 9, 9, 9]))
    assert (d["action"], d["index"], d["reason"]) == ("drop", 1, "unique")
    assert d["s_final"] == 0.05


def test_cost_margin_picks_the_lowest_J():
    d = gate.outlier_drop(RING, (0, 0), FAIL, _loo([0.01, 0.02, 0.9, 0.9], [8.0, 3.9, 9, 9]))
    assert (d["action"], d["index"], d["reason"]) == ("drop", 1, "J")


def test_similar_J_nearest_inner_image_is_dropped():
    pos = RING.copy()
