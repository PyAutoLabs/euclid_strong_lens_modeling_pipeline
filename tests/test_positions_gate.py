def _dataset_with_positions(sample_path, name):
    d = sample_path / name
    d.mkdir(parents=True, exist_ok=True)
    shutil.copy(EXAMPLE_PATH / f"{EXAMPLE_DATASET}.fits", d / f"{name}.fits")
    shutil.copy(EXAMPLE_PATH / "info.json", d / "info.json")
    shutil.copy(
        FIXTURES / "Tile102012028RA0853629092626DECNEG0587974678810" / "positions.json",
        d / "positions.json",
    )
    return d


def test_load_vis_dataset_reads_the_sidecar_and_falls_back(tmp_sample):
    import util

    d = _dataset_with_positions(tmp_sample, "with_positions")
    raw = util.load_vis_dataset(dataset_name="with_positions", sample_name=TMP_SAMPLE)
    assert raw.positions_likelihood_list[0].threshold == 0.2
    assert len(raw.positions_likelihood_list[0].positions) == 4

    # The gate's light centre is the loader's dataset_centre.
    assert gate.light_centre_from_dataset(d) == pytest.approx(tuple(raw.dataset_centre), abs=1e-9)

    _write_meta(d)
    gated = util.load_vis_dataset(dataset_name="with_positions", sample_name=TMP_SAMPLE)
    assert gated.positions_likelihood_list[0].threshold == pytest.approx(0.34)
    assert len(gated.positions_likelihood_list[0].positions) == 2

    _write_meta(d, status="n_lt_2", positions_used=[], threshold=None)
    off = util.load_vis_dataset(dataset_name="with_positions", sample_name=TMP_SAMPLE)
    assert off.positions_likelihood_list is None
