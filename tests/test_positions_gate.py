def solve_images(params, source, centre=(0.0, 0.0), extent=3.0, n=25):
    """All image-plane solutions of the lens equation for a point source."""
    sols = []
    for y0 in np.linspace(-extent, extent, n):
        for x0 in np.linspace(-extent, extent, n):
            res = least_squares(
                lambda t: gate.source_positions(t[None, :], params)[0] - np.asarray(source),
                [y0, x0],
                xtol=1e-14,
                ftol=1e-14,
            )
            if np.hypot(*res.fun) < 1e-9 and np.hypot(*res.x) > 0.05:
                if all(np.hypot(*(res.x - s)) > 1e-4 for s in sols):
                    sols.append(res.x)
    return np.array(sols) + np.asarray(centre)


