def test_sis_double_traces_and_keeps_at_the_floor():
    meta = gate.gate_positions(sis_double(), CENTRE)
    assert meta["s_min"] < 1e-3
    assert meta["status"] == "keep"
    assert meta["threshold"] == 0.3
    assert meta["dropped"] == []
    assert len(meta["positions_used"]) == 2


def test_sie_quad_traces_and_keeps_at_the_floor(quad):
    # A seed tracing the set to < EASY (0.02") is accepted without the minimax
    # polish (prototype behaviour): s_min is exact only to that level here.
    fit = gate.quick_fit(quad, CENTRE)
    assert fit["s_min"] < gate.EASY
    meta = gate.gate_positions(quad, CENTRE)
    assert meta["status"] == "keep"
    assert meta["threshold"] == 0.3
    assert len(meta["positions_used"]) == 4


def test_nucleus_image_is_cut(quad):
    pos = np.vstack([quad, [CENTRE[0] + 0.1, CENTRE[1]]])
    meta = gate.gate_positions(pos, CENTRE)
    assert meta["dropped"] == [
        dict(index=4, y=round(CENTRE[0] + 0.1, 4), x=round(CENTRE[1], 4), reason="central_cut")
    ]
    assert meta["status"] == "drop"
    assert meta["threshold"] == 0.3
    assert len(meta["positions_used"]) == 4


def test_image_just_outside_the_cut_is_not_cut():
    kept, cut = gate.central_cut([[0.0, 0.16], [0.0, 0.14], [1.0, 1.0]], (0.0, 0.0))
    assert kept == [0, 2] and cut == [1]


def test_spurious_image_is_dropped_exactly(quad):
    pos = np.vstack([quad[:2], [[CENTRE[0] + 2.6, CENTRE[1] + 1.9]], quad[2:]])
    meta = gate.gate_positions(pos, CENTRE)
    assert meta["s_min_all"] > 0.2
    assert [d["index"] for d in meta["dropped"]] == [2]
    assert meta["dropped"][0]["reason"].startswith("outlier_")
    assert meta["status"] == "drop"
    assert meta["s_min"] < gate.EASY
    assert meta["threshold"] == 0.3
    assert len(meta["positions_used"]) == 4


def test_untraceable_pair_goes_to_review():
    # Two images on the same side of the lens along one ray cannot be traced.
    pos = np.array([[CENTRE[0], CENTRE[1] + 1.0], [CENTRE[0], CENTRE[1] + 3.0]])
    meta = gate.gate_positions(pos, CENTRE)
    assert meta["status"] == "review"
    assert meta["review_reason"] == "n2_fail"
    assert meta["dropped"] == []


def test_fewer_than_two_survivors_turns_the_penalty_off():
    pos = np.array([[CENTRE[0] + 0.05, CENTRE[1]], [CENTRE[0], CENTRE[1] + 1.3]])
    meta = gate.gate_positions(pos, CENTRE)
    assert meta["status"] == "n_lt_2"
    assert meta["threshold"] is None
    assert len(meta["positions_used"]) == 1
    assert meta["dropped"][0]["reason"] == "central_cut"


