def test_plausibility_flag():
    fit = dict(s_min=0.05, J=20.0)
    assert gate.plausibility_flag(fit, _loo([0] * 4, [9.9, 15, 16, 17])) == 0
    assert gate.plausibility_flag(fit, _loo([0] * 4, [10.1, 15, 16, 17])) is None  # dJ < 10
    assert gate.plausibility_flag(fit, _loo([0] * 4, [9.0, 12.0, 16, 17])) is None  # not unique


