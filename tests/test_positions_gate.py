def sis_double(theta_e=1.0, beta=0.3, centre=CENTRE):
    """Analytic SIS double: images at r = theta_E +/- beta on either side of the lens."""
    return np.array(
        [[centre[0], centre[1] + theta_e + beta], [centre[0], centre[1] - (theta_e - beta)]]
    )


