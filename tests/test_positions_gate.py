def test_max_separation_matches_pyautolens_tracer():
    import autolens as al

    pos = np.array([[1.1, 0.3], [-0.8, -0.6], [0.2, -1.2], [-0.4, 1.0]])
    for p in ((1.1, 0.2, -0.1, 0.05, 0.12), (0.7, -0.3, 0.25, -0.2, 0.1), (2.5, 0.0, 0.0, 0.0, 0.0)):
        te, e0, e1, g1, g2 = p
        lens = al.Galaxy(
            redshift=0.5,
            mass=al.mp.Isothermal(centre=CENTRE, ell_comps=(e0, e1), einstein_radius=te),
        )
        field = al.MassField(redshift=0.5, shear=al.mp.ExternalShear(gamma_1=g1, gamma_2=g2))
        tracer = al.Tracer(galaxies=[lens, al.Galaxy(redshift=1.0)], fields=[field])
        traced = np.asarray(tracer.traced_grid_2d_list_from(grid=al.Grid2DIrregular(values=pos))[-1])
        d = np.hypot(traced[:, None, 0] - traced[None, :, 0], traced[:, None, 1] - traced[None, :, 1])
        assert gate.max_separation(pos - np.array(CENTRE), p) == pytest.approx(d.max(), abs=1e-9)


def test_brightest_sub_pixel_centre_matches_autoarray():
    import autolens as al

    rng = np.random.default_rng(3)
    for centre in ((0.0, 0.0), (0.35, -0.42), (-1.1, 0.8)):
        img = rng.uniform(0.1, 1.0, (40, 40))
        arr = al.Array2D.no_mask(values=img, pixel_scales=0.1)
        expected = arr.brightest_sub_pixel_coordinate_in_region_from(
            region=(centre[0] - 0.3, centre[0] + 0.3, centre[1] - 0.3, centre[1] + 0.3),
            box_size=2,
        )
        got = gate.brightest_sub_pixel_centre(img, 0.1, centre)
        assert got == pytest.approx(tuple(expected), abs=1e-9)


